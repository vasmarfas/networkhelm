// the router's words for the texts of the bundled windows; a text the router has no word for stays as the pack has it,
// or in Russian takes the word above
internal fun wordsOf(dictionary: JsonElement?, language: String): Map<String, String> = buildMap {
    if (language == "ru") putAll(RUSSIAN)
    for ((text, key) in KEYS + SERVICE_KEYS + APP_KEYS + SYSTEM_KEYS + TAGS.entries.associate { (tag, text) -> text to "administrator.editor.tags.$tag" }) {
        val word = key.split('.').fold(dictionary) { at, part -> (at as? JsonObject)?.get(part) }
        (word as? JsonPrimitive)?.contentOrNull?.let { put(text, it) }
    }
}
