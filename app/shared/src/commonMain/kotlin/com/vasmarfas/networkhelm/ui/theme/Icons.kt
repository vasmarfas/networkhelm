enum class IconTint { Text, Muted, Accent, Success, Warning, Danger }

class ThemeIcon(val vector: ImageVector, val tint: IconTint?)

fun themeIcon(spec: String): ThemeIcon? {
    val parts = spec.split(':')
    val picture = parts[0] == PICTURE
    val vector = (if (picture) pictureVector(parts.getOrNull(1), parts.getOrNull(2)) else IconSet[parts[0]]) ?: return null
    val colour = parts.getOrNull(if (picture) 3 else 1).orEmpty()
    if (colour.isEmpty()) return ThemeIcon(vector, null)
    return IconTint.entries.firstOrNull { it.name.equals(colour, ignoreCase = true) }?.let { ThemeIcon(vector, it) }
}

fun Palette.tintOf(icon: ThemeIcon?): Color? = icon?.tint?.let(::tint)

fun Palette.tint(tint: IconTint): Color = when (tint) {
    IconTint.Text -> text
    IconTint.Muted -> muted
    IconTint.Accent -> accent
    IconTint.Success -> success
    IconTint.Warning -> warning
    IconTint.Danger -> danger
}
